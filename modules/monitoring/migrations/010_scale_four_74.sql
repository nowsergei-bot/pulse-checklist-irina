-- Решение кафедры 20.10.2026: «4» от 74 % (37 из 50 = 74 % → «4»). Остальные пороги прежние:
-- «5» от 90 %, «3» от 50 %, ниже «2». Процент по-прежнему итог / максимум × 100, округление до целого.
-- Отметки не хранятся, поэтому все работы сразу считаются по новому порогу. Баллы не меняются.

UPDATE monitoring.grade_scale_rows
SET min_percent = 74
WHERE mark = '4'
  AND scale_id IN (SELECT id FROM monitoring.grade_scales WHERE name = 'Положение о системе оценивания');
